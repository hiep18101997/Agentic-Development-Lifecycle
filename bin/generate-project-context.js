#!/usr/bin/env node
'use strict';

const fs   = require('fs');
const path = require('path');
const pc   = require('picocolors');

const ROOT     = path.resolve(__dirname, '..');
const DECISIONS_DIR = path.join(ROOT, 'docs', 'decisions');
const OUT      = path.join(ROOT, 'docs', 'project-context.md');

// ── ADR parser ──────────────────────────────────────────────

// Extracts adrId/date/status from YAML frontmatter, the title from the
// first `# ADR-...:` heading, and a one-line summary from the
// `**Chọn phương án**: ...` line under `## Quyết định` (VN template) —
// falls back to `**Decision**: ...` (EN template) when present.
function parseAdr(fp) {
  let content;
  try { content = fs.readFileSync(fp, 'utf8'); }
  catch { return null; }

  const fmMatch = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  const fm = {};
  if (fmMatch) {
    for (const line of fmMatch[1].split(/\r?\n/)) {
      const m = line.match(/^([A-Za-z]+):\s*(.*)$/);
      if (m) fm[m[1].trim()] = m[2].trim();
    }
  }

  const titleMatch = content.match(/^#\s+ADR-[^\r\n:]*:?\s*(.+)$/m) || content.match(/^#\s+(.+)$/m);
  const summaryMatch = content.match(/\*\*(?:Chọn phương án|Decision)\*\*:\s*(.+)/);

  return {
    file:    path.basename(fp),
    adrId:   fm.adrId || path.basename(fp).match(/ADR-\d+/)?.[0] || path.basename(fp, '.md'),
    date:    fm.date || null,
    status:  fm.status || 'Unknown',
    title:   titleMatch ? titleMatch[1].trim() : path.basename(fp, '.md'),
    summary: summaryMatch ? summaryMatch[1].trim() : null,
  };
}

function scanAdrs(dir) {
  let entries;
  try { entries = fs.readdirSync(dir); }
  catch { return []; }

  return entries
    .filter(f => /^ADR-.*\.md$/i.test(f))
    .map(f => parseAdr(path.join(dir, f)))
    .filter(Boolean)
    .sort((a, b) => (a.adrId > b.adrId ? 1 : a.adrId < b.adrId ? -1 : 0));
}

// ── Markdown builder ────────────────────────────────────────

function buildMarkdown(adrs) {
  const generatedAt = new Date().toISOString().replace('T', ' ').slice(0, 16) + ' UTC';

  const lines = [
    '<!-- AUTO-GENERATED by bin/generate-project-context.js — DO NOT HAND-EDIT. Re-run: node bin/generate-project-context.js -->',
    '',
    '# Project Context Digest',
    '',
    `_Generated: ${generatedAt}_`,
    '',
    'Tóm tắt các Architecture Decision Record (ADR) hiện có, sinh tự động từ `docs/decisions/ADR-*.md`. File này KHÔNG phải nguồn thật (source of truth) — nếu lệch với ADR gốc, ADR gốc luôn thắng. Chạy lại `node bin/generate-project-context.js` sau khi tạo/cập nhật ADR.',
    '',
    '---',
    '',
  ];

  if (adrs.length === 0) {
    lines.push(
      '## ADRs',
      '',
      'No ADRs recorded yet — this file will populate as /arch-adr creates decisions.',
      ''
    );
    return lines.join('\n');
  }

  const accepted = adrs.filter(a => a.status.toLowerCase() === 'accepted');
  const others    = adrs.filter(a => a.status.toLowerCase() !== 'accepted');

  lines.push('## Accepted / Current ADRs', '');
  if (accepted.length === 0) {
    lines.push('_Chưa có ADR nào ở trạng thái Accepted._', '');
  } else {
    lines.push('| ADR | Title | Date | Summary |', '|-----|-------|------|---------|');
    for (const a of accepted) {
      const summary = (a.summary || '—').replace(/\|/g, '\\|');
      lines.push(`| [${a.adrId}](decisions/${a.file}) | ${a.title.replace(/\|/g, '\\|')} | ${a.date || '—'} | ${summary} |`);
    }
    lines.push('');
  }

  if (others.length > 0) {
    lines.push('## Other ADRs (Proposed / Deprecated / Superseded)', '');
    lines.push('| ADR | Title | Status | Date | Summary |', '|-----|-------|--------|------|---------|');
    for (const a of others) {
      const summary = (a.summary || '—').replace(/\|/g, '\\|');
      lines.push(`| [${a.adrId}](decisions/${a.file}) | ${a.title.replace(/\|/g, '\\|')} | ${a.status} | ${a.date || '—'} | ${summary} |`);
    }
    lines.push('');
  }

  lines.push('## Active constraints', '');
  const constraintLines = accepted
    .filter(a => a.summary)
    .map(a => `- **${a.adrId}** (${a.title}): ${a.summary}`);
  if (constraintLines.length === 0) {
    lines.push('_Chưa xác định được constraint cụ thể từ ADR hiện có — xem trực tiếp `docs/decisions/`._', '');
  } else {
    lines.push(...constraintLines, '');
  }

  return lines.join('\n');
}

// ── Main ────────────────────────────────────────────────────

function main() {
  const adrs = scanAdrs(DECISIONS_DIR);
  const markdown = buildMarkdown(adrs);
  fs.writeFileSync(OUT, markdown, 'utf8');

  console.log(pc.cyan('\n  Agentic Development Lifecycle — Project Context Digest\n'));
  console.log(`  ${pc.green('◆')} ${pc.cyan(OUT)}`);
  console.log(`  ${pc.dim(`${adrs.length} ADR(s) scanned from docs/decisions/`)}`);
  console.log();
}

main();
